function canonicalXLanguage(value) {
  const code = String(value || "").trim().toLowerCase().replaceAll("_", "-");
  if (LANGUAGE_BY_CODE.has(code)) return code;
  if (ALIASES[code]) return ALIASES[code];
  const base = code.split("-")[0];
  if (LANGUAGE_BY_CODE.has(base)) return base;
  if (ALIASES[base]) return ALIASES[base];
  return "";
}

function readStoredLanguage() {
  try {
    return canonicalXLanguage(localStorage.getItem("panel-lang-choice"));
  } catch {
    return "";
  }
}

function systemXLanguage() {
  try {
    return canonicalXLanguage(navigator.language);
  } catch {
    return "";
  }
}

const i18nState = { language: readStoredLanguage() || systemXLanguage() || "zh-cn" };

function xLanguage() {
  return i18nState.language;
}

function setXLanguage(value) {
  const code = canonicalXLanguage(value);
  if (code) i18nState.language = code;
  return i18nState.language;
}

function messageLanguage() {
  if (UI_MESSAGES[i18nState.language]) return i18nState.language;
  if (i18nState.language.startsWith("zh")) return "zh-cn";
  return "en";
}

function t(key, vars) {
  const language = messageLanguage();
  const template = UI_MESSAGES[language][key] ?? UI_MESSAGES.en[key] ?? UI_MESSAGES["zh-cn"][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => vars[name] == null ? match : String(vars[name]));
}

function languagePresentation() {
  const language = LANGUAGE_BY_CODE.get(i18nState.language);
  return {
    html: language?.html || "en",
    dir: language?.dir || "ltr",
    locale: language?.locale || "en",
  };
}
